// Writes docs/low-res-needs-reexport.md from data/image-manifest.json and the
// rendered widths measured on the live site (docs/reference-shots/measurements.json).
import { readFile, writeFile } from "node:fs/promises";

const manifest = JSON.parse(await readFile("data/image-manifest.json", "utf8"));
const products = JSON.parse(await readFile("data/products.json", "utf8"));
const m = JSON.parse(await readFile("docs/reference-shots/measurements.json", "utf8"));

// Largest rendered width of each image role across the captured pages (CSS px).
const maxOf = (key) => Math.max(...Object.values(m).map((v) => v[key] ?? 0));
const rendered = {
  product: Math.max(maxOf("productImage"), maxOf("gridTile")),
  slideshow: maxOf("slideshow"),
  logo: maxOf("logo"),
};

const flag = (w, h, renderedWidth) => {
  const reasons = [];
  if (Math.max(w, h) < 1000) reasons.push("long edge under 1000 px");
  if (w < 2 * renderedWidth) reasons.push(`width under 2x rendered (${Math.round(renderedWidth)} px)`);
  return reasons;
};

const low = [];
// Tier 1: under 800 px wide (soft at any size); tier 2: long edge under 1000 px; tier 3: only under 2x rendered width.
const tier = (img) => (img.width < 800 ? 1 : Math.max(img.width, img.height) < 1000 ? 2 : 3);
const short = [];
products.forEach((p, i) => {
  for (const img of manifest.products[p.slug]) {
    const reasons = flag(img.width, img.height, rendered.product);
    if (reasons.length) low.push({ n: i + 1, name: p.name, slug: p.slug, img, reasons, tier: tier(img) });
    if (img.width < img.feedWidth || img.height < img.feedHeight) short.push({ n: i + 1, slug: p.slug, img });
  }
});
const siteLow = Object.entries(manifest.site)
  .filter(([k]) => k !== "og-image")
  .map(([k, img]) => ({ k, img, reasons: flag(img.width, img.height, rendered[k.startsWith("slideshow") ? "slideshow" : "logo"]) }))
  .filter((x) => x.reasons.length);

const lines = [
  "# Images that need a re-export",
  "",
  "Generated by `scripts/low-res-report.mjs`. Sizes are the largest CDN-served copies (not owner uploads).",
  "Nothing is upscaled; these render at their native size until the owner supplies larger files.",
  "",
  `Rendered widths measured on live (CSS px): product image ${rendered.product}, slideshow ${rendered.slideshow}, logo ${Math.round(rendered.logo)}.`,
  "",
  "## Low resolution (long edge under 1000 px, or width under 2x rendered width)",
  "",
  ...[1, 2, 3].flatMap((t) => {
    const rows = low.filter((x) => x.tier === t);
    const title = ["", "Tier 1: under 800 px wide (re-export first)", "Tier 2: long edge under 1000 px", "Tier 3: only under 2x the rendered width (soft on high-DPI screens)"][t];
    return [
      `### ${title}`,
      "",
      `Products: ${[...new Set(rows.map((x) => x.n))].join(", ")} (${rows.length} images). Request 2000 px or larger.`,
      "",
      "| # | Product | Image | Size | Why |",
      "|---|---------|-------|------|-----|",
      ...rows.map((x) => `| ${x.n} | ${x.name} (\`${x.slug}\`) | ${x.img.index} | ${x.img.width}×${x.img.height} | ${x.reasons.join("; ")} |`),
      "",
    ];
  }),
  "",
  "### Site images",
  "",
  "| Image | Size | Why |",
  "|-------|------|-----|",
  ...siteLow.map((x) => `| ${x.k} | ${x.img.width}×${x.img.height} | ${x.reasons.join("; ")} |`),
  "",
  "The logo should ideally come as a vector (SVG) or at least 1000 px wide.",
  "",
  "## Smaller than the feed size (CDN 3200 px cap)",
  "",
  "The CDN never serves more than 3200 px on the long edge. These copies are still larger than any",
  "rendered size, so they look sharp on the web, but they are not the full uploads.",
  "",
  "| # | Product | Image | Feed size | Served size |",
  "|---|---------|-------|-----------|-------------|",
  ...short.map((x) => `| ${x.n} | \`${x.slug}\` | ${x.img.index} | ${x.img.feedWidth}×${x.img.feedHeight} | ${x.img.width}×${x.img.height} |`),
  "",
];
await writeFile("docs/low-res-needs-reexport.md", lines.join("\n"));
for (const t of [1, 2, 3]) console.log(`tier ${t}: products ${[...new Set(low.filter((x) => x.tier === t).map((x) => x.n))].join(", ")} (${low.filter((x) => x.tier === t).length} images)`);
console.log(`low-res products: ${[...new Set(low.map((x) => x.n))].join(", ")} (${low.length} images); site: ${siteLow.map((x) => x.k).join(", ")}; smaller than feed: ${short.length}`);
